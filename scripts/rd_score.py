"""Score the CMNeXt row against plan/PREREG-removal-dropout.md.

WRITTEN BEFORE ANY ARM FINISHED. That is the point: the contrasts, the margins and the verdict rule
are fixed while the data is still unknown, so no researcher degree of freedom survives to the moment
the numbers land. Do not edit this file to change how a verdict is computed after seeing a result --
record a supersede instead.

Two gates run BEFORE any verdict, and either one blocks the claim:

  1. CONVERGENCE. The prereg flagged that `removal` starts far further from the audited checkpoint
     than `zero` does (epoch-1 loss 1.93 vs 0.077), because R hands the decoder a feature
     distribution it has never seen. If `removal`'s final training loss has not plateaued, the
     comparison is an optimization artifact and NO method claim may be made from it.
  2. DROP-RATE PARITY. Both arms must have realized the same dropout fraction; they share a mask
     generator, so a mismatch means the shared-mask guarantee broke.

    python3 scripts/rd_score.py
"""
import json
import re
import statistics as st
import sys
from math import sqrt
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
RUNS = PROJECT / "results" / "removal_dropout"

# Declared margins, inherited from TARGET.md S3 and NOT re-derived here.
DECLARED = {"clean": 0.88, "missing": 1.49}
T = {4: (2.776, 0.941), 3: (3.182, 0.978), 2: (4.303, 1.061)}


def mde(a, b, declared):
    df = len(a) + len(b) - 2
    if df not in T or len(a) < 2 or len(b) < 2:
        return None, declared
    t1, t2 = T[df]
    sp = sqrt(((len(a) - 1) * st.stdev(a) ** 2 + (len(b) - 1) * st.stdev(b) ** 2) / df)
    m = (t1 + t2) * sqrt(1 / len(a) + 1 / len(b)) * sp
    return m, max(m, declared)


def final_losses(run_dir):
    """Last reported training loss, and the mean of the last 10, to judge plateau."""
    lg = run_dir / "train.log"
    if not lg.exists():
        return None, None
    vals = [float(m) for m in re.findall(r"Loss:\s*([0-9.]+)", lg.read_text(errors="ignore"))]
    if not vals:
        return None, None
    tail = vals[-200:]
    return vals[-1], (st.mean(tail[:100]), st.mean(tail[100:])) if len(tail) >= 200 else None


def main():
    ev_path = RUNS / "eval.json"
    if not ev_path.exists():
        print("no eval.json yet — run scripts/rd_eval.py first")
        return 1
    ev = json.loads(ev_path.read_text())

    arms = {"removal": {}, "zero": {}}
    for tag, rec in ev.items():
        arm = "removal" if "_removal_" in tag else "zero"
        for cond in ("clean", "zero_in", "removal_R"):
            if rec.get(cond) is not None:
                arms[arm].setdefault(cond, {})[tag] = rec[cond]

    print("PER-SEED RAW VALUES (never only mean +- sd)")
    for arm in ("removal", "zero"):
        for cond, d in sorted(arms[arm].items()):
            vals = ", ".join(f"{k.split('_s')[-1]}={v:.2f}" for k, v in sorted(d.items()))
            print(f"  {arm:8s} {cond:10s} {vals}")

    # ---- GATE 1: convergence
    print("\nGATE 1 — convergence (the prereg's flagged optimization confound)")
    blocked = False
    for tag in sorted(ev):
        last, halves = final_losses(RUNS / tag)
        if last is None:
            print(f"  {tag}: no loss lines found — cannot certify convergence")
            blocked = True
            continue
        note = ""
        if halves:
            first_half, second_half = halves
            drift = first_half - second_half
            note = f" | last-200 drift {drift:+.4f}"
            if abs(drift) > 0.05 * max(1e-9, first_half):
                note += "  <-- STILL DESCENDING"
                blocked = True
        print(f"  {tag}: final loss {last:.4f}{note}")

    # ---- GATE 2: drop-rate parity
    print("\nGATE 2 — drop-rate parity")
    fracs = {}
    for tag in sorted(ev):
        f = RUNS / tag / "done.json"
        if f.exists():
            fracs[tag] = json.loads(f.read_text()).get("realized_drop_fraction")
    if fracs:
        lo, hi = min(fracs.values()), max(fracs.values())
        print(f"  realized drop fraction range: {lo:.4f} .. {hi:.4f}")
        if hi - lo > 0.02:
            print("  MISMATCH — the shared-mask guarantee broke; arms did not see the same drops")
            blocked = True

    # ---- the contrasts
    print("\nCONTRASTS (removal − zero), operative margin = max(declared, realized MDE)")
    verdicts = {}
    pairs = [("removal_R", "zero_in", "HEADLINE: each arm in the mode it was trained for"),
             ("zero_in", "zero_in", "transfer: both under the standard benchmark condition"),
             ("removal_R", "removal_R", "transfer: both under the named removal"),
             ("clean", "clean", "non-regression floor")]
    for c_rem, c_zero, label in pairs:
        A = list(arms["removal"].get(c_rem, {}).values())
        B = list(arms["zero"].get(c_zero, {}).values())
        if len(A) < 2 or len(B) < 2:
            print(f"  {label}: not scoreable (n={len(A)}/{len(B)})")
            continue
        d = st.mean(A) - st.mean(B)
        dec = DECLARED["clean"] if c_rem == "clean" else DECLARED["missing"]
        realized, operative = mde(A, B, dec)
        resolves = abs(d) > operative
        verdicts[label] = (d, operative, resolves)
        print(f"  {label}")
        print(f"    removal[{c_rem}] {st.mean(A):6.2f}  −  zero[{c_zero}] {st.mean(B):6.2f}  "
              f"=  {d:+.2f}")
        print(f"    declared {dec:.2f} | realized MDE {realized:.2f} | operative {operative:.2f}"
              f"  ->  {'RESOLVED' if resolves else 'unresolved'}")

    # ---- the pre-registered verdict
    print("\n" + "=" * 72)
    if blocked:
        print("VERDICT: CONFOUNDED / BLOCKED. A gate failed above. Per the prereg no method claim")
        print("may be made from these runs; the remedy is a longer schedule for BOTH arms equally.")
        return 2
    head = verdicts.get("HEADLINE: each arm in the mode it was trained for")
    if head is None:
        print("VERDICT: not scoreable.")
        return 1
    d, op, res = head
    if res and d > 0:
        print("VERDICT: R1 SUPPORTED. Training on the named removal beats training on the")
        print("sentinel on an architecture where zero-fill is audited NON-equivalent.")
        print("Removal equivalence is a TRAINING-DESIGN PRINCIPLE, not only an audit criterion.")
    elif res and d < 0:
        print("VERDICT: R1 REFUTED, and against us. The sentinel beat the true removal. The")
        print("framework does not predict this and it must be reported, not smoothed.")
    else:
        print("VERDICT: UNRESOLVED at this resolution. Per the prereg the paper reverts to the")
        print("audit + diagnosis contribution. NO search for a better removal site is permitted.")
    print("=" * 72)
    return 0


if __name__ == "__main__":
    sys.exit(main())
